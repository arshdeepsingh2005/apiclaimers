def create_app(config_class=Config):
    """Create and configure the Flask application."""
    app = Flask(__name__, template_folder=str(TEMPLATE_DIR))
    app.config.from_object(config_class)

    # API-Claimer: accept all origins (no Cloudflare; many connecting hosts).
    if config_class.API_CLAIMER_MODE:
        CORS(app, origins='*', supports_credentials=False)
    else:
        CORS(app, origins=config_class.ALLOWED_ORIGINS, supports_credentials=True)

    # SocketIO must be bound to the app before run() is used
    socketio.init_app(app)

    # Rate limiting — per-IP and per-username
    from app.rate_limit import limiter
    limiter.init_app(app)

    # Register blueprints
    from app.routes.main import main_bp
    from app.routes.api import api_bp
    from app.routes.internal import internal_bp, xr9k_bp
    from app.routes.websocket_routes import ws_bp
    from app.routes.sse_routes import sse_bp
    from app.routes.api_slots import api_slots_bp  # API-Claimer product
    from app.routes.api_customer import api_customer_bp  # slot-sales (bot + Mini App)
    # NOTE: the public OxaPay webhook lives on the BOT service (Service 2) now,
    # so the heavy/spammy callback traffic never hits this backend. Money is
    # still moved ONLY here, via the internal /api/xr9k/topup/credit endpoint,
    # which independently re-verifies with OxaPay before crediting.

    app.register_blueprint(main_bp)
    app.register_blueprint(api_bp)
    app.register_blueprint(internal_bp)
    app.register_blueprint(xr9k_bp)
    app.register_blueprint(ws_bp)
    app.register_blueprint(sse_bp)
    app.register_blueprint(api_slots_bp)  # API-Claimer product
    app.register_blueprint(api_customer_bp)  # slot-sales (bot + Mini App)

    # Register /_tmc namespace by importing the module (decorators self-register).
    from app.routes import tmc_routes  # noqa: F401

    # ── Global request-rate flood monitor (best-effort, alerts the admin) ──
    # Counts every incoming HTTP request (incl. WS handshakes) into a fixed-size
    # in-memory ring buffer and pings the admin if the 60s total crosses the
    # threshold. Wrapped so monitoring can NEVER break request handling.
    from app.utils.attack_monitor import record_request as _record_request

    @app.before_request
    def _attack_monitor_before_request():
        try:
            _record_request()
        except Exception:
            pass
        return None

    import logging

    # init_db() runs DDL (create_all) against Supabase. It is NOT safe on the
    # live request path — a slow pooler handshake here blocks worker boot past
    # Gunicorn's timeout, which is what made Render fail to detect the port.
    # Gate it behind RUN_INIT_DB=1 so it only runs on explicit first-deploy.
    try:
        with app.app_context():
            if os.environ.get('RUN_INIT_DB') == '1':
                init_db()
                # Ensure the claims table on the SECOND DB (no-op if
                # CLAIMS_DATABASE_URL unset; never raises — degrades to the
                # in-memory fallback rather than blocking boot).
                init_claims_db()
            # Self-heal the api_claims ownership-snapshot column on EVERY boot in
            # API_CLAIMER_MODE (idempotent ADD COLUMN IF NOT EXISTS) so an existing
            # DB gets it without a manual migration / RUN_INIT_DB re-run. Cheap and
            # non-fatal; needed before /stats or any claim recording runs.
            if Config.API_CLAIMER_MODE:
                ensure_api_claim_columns()
                ensure_api_order_columns()      # cart_id for multi-slot carts (idempotent)
                # Read-only: warn (once) if the operational stats index is missing.
                # Never builds/locks/blocks — the index ships via MIGRATIONS.md.
                warn_if_stats_index_missing()
            user_service.start()
    except Exception as e:
        logging.error(
            f"Error during database/service initialization: {e}",
            exc_info=True
        )



    # Send startup notification to Telegram channel
    try:
        from app.utils.telegram import notify_startup
        notify_startup()
    except Exception as e:
        import logging as _log
        _log.warning(f"Telegram startup notify failed: {e}")

    return app


# ---------------------------------------------------------------------------
# Worker 1: Active-Disconnect-Worker
# Runs every 120 seconds.
# Checks only CURRENTLY CONNECTED users (WebSocket + SSE) against DB.
# 120s is a deliberate tradeoff against Supabase Free's Nano pooler (15 backend
# slots) — a 10s cadence produced periodic `Connection timed out` bursts when
# this worker coincided with cache sweeps and user lookups. 120s gives the
# pooler breathing room and still kicks revoked users within ~2 minutes.
# ---------------------------------------------------------------------------

def _start_active_disconnect_worker(app):
    """
    Background worker that disconnects users removed from the database.

    Scope: users who are CURRENTLY connected via WebSocket or SSE.
    Interval: every 120 seconds — tuned for Supabase Free's 15-slot pooler.

    For each cycle:
      1. Snapshots all connected WebSocket + SSE usernames.
      2. Single batch DB query to find which still exist.
      3. Guards against transient DB failures (distinguishes DB-down from
         user-genuinely-deleted via a health-check count query).
      4. Evicts removed users from UserService cache BEFORE disconnecting
         so that an immediate reconnect attempt hits DB and is rejected.
      5. Terminates their WebSocket connections.
      6. Terminates their SSE connections.
    """
    import threading
    import time
    import logging

    logger = logging.getLogger(__name__)

    # API_CLAIMER_MODE: this is a MAIN-PRODUCT reaper that validates connected
    # clients against the legacy app_users table. In API-Claimer mode the only
    # non-/_tmc client is the operator's ingest console (username 'ingest'), which
    # isn't an app_user — so this worker would disconnect it every cycle. Skip it
    # entirely (userscript account removal is handled by license_deleted events).
    if Config.API_CLAIMER_MODE:
        logger.info("Active-Disconnect-Worker NOT started (API_CLAIMER_MODE)")
        return

    def active_disconnect_loop():
        from app.websocket_manager import websocket_manager
        from app.sse_manager import sse_manager
        from app import socketio
        from app.config import Config

        while True:
            try:
                time.sleep(120)

                # Heartbeat — confirms the worker greenlet is alive and
                # cycling. If you don't see this every ~2 minutes in logs,
                # the worker is dead/starved and that's why nothing gets
                # disconnected.
                logger.info("Active disconnect: cycle start")

                # ----------------------------------------------------------
                # Step 1: Snapshot connected users — WebSocket
                # dict() copy: safe to iterate even if clients mutated
                # concurrently.
                # ----------------------------------------------------------
                connected_users = set()
                sids_to_disconnect = []

                clients_snapshot = dict(websocket_manager.clients)
                for sid, client_info in clients_snapshot.items():
                    username = client_info.get('username')
                    if username:
                        connected_users.add(username)

                # ----------------------------------------------------------
                # Step 2: Snapshot connected users — SSE
                # Lock held only for the copy; released before any DB work.
                # ----------------------------------------------------------
                # Derive the SSE snapshot from connection_health rather than
                # connections. In production we observed self.connections going
                # empty while self.connection_health remained populated — the
                # three dicts drifted out of sync under heavy greenlet
                # concurrency even though add_connection/remove_connection hold
                # the lock. connection_health is the dict /sse-pong looks up,
                # so if a connection can pong, it's live — that makes it the
                # reliable source of truth for "who is actually connected".
                with sse_manager.lock:
                    sse_snapshot = {}
                    for conn_id, health in sse_manager.connection_health.items():
                        username = health.get('username')
                        if not username:
                            continue
                        sse_snapshot.setdefault(username, []).append(conn_id)
                for username in sse_snapshot:
                    if username:
                        connected_users.add(username)

                # /_v snapshot — sid->username for the new broadcast namespace
                from app._v_manager import _v_manager
                v_snapshot = {}
                for sid, username in _v_manager.all_sids():
                    if not username:
                        continue
                    v_snapshot.setdefault(username, []).append(sid)
                    connected_users.add(username)

                logger.info(
                    f"Active disconnect: {len(connected_users)} connected users "
                    f"({len(clients_snapshot)} WS, {len(sse_snapshot)} SSE, "
                    f"{len(v_snapshot)} V) | "
                    f"sse_mgr_id={id(sse_manager)} | "
                    f"ws_mgr_id={id(websocket_manager)} | "
                    f"pid={os.getpid()}"
                )

                if not connected_users:
                    continue

                # ----------------------------------------------------------
                # Step 3: Skip when auth is disabled
                # ----------------------------------------------------------
                if Config.AUTH_DISABLED:
                    logger.info("Active disconnect: AUTH_DISABLED=true — skipping")
                    continue

                # ----------------------------------------------------------
                # Step 4: Batch DB query — one round-trip for all connected
                # ----------------------------------------------------------
                try:
                    with app.app_context():
                        from app.database import SessionLocal
                        with SessionLocal() as session:
                            valid_users = session.execute(
                                select(User.username).where(
                                    User.username.in_(connected_users)
                                )
                            ).scalars().all()
                            valid_users_set = set(valid_users)

                            # ----------------------------------------------
                            # Transient failure guard:
                            # If none of the connected users were found, the
                            # DB may be returning bad results rather than all
                            # users being genuinely deleted simultaneously.
                            # Verify with a cheap count before disconnecting.
                            # ----------------------------------------------
                            if not valid_users_set and connected_users:
                                try:
                                    db_alive = session.execute(
                                        select(func.count()).select_from(User)
                                    ).scalar()
                                    if db_alive == 0:
                                        logger.warning(
                                            "Active disconnect: DB health check "
                                            "shows 0 users — skipping "
                                            "(transient failure)"
                                        )
                                        continue
                                    # db_alive > 0: DB is up, users were
                                    # genuinely deleted — fall through.
                                except Exception:
                                    logger.warning(
                                        "Active disconnect: DB health check "
                                        "failed — skipping (transient failure)"
                                    )
                                    continue

                            users_to_disconnect = connected_users - valid_users_set

                            logger.info(
                                f"Active disconnect: DB returned {len(valid_users_set)} "
                                f"valid users out of {len(connected_users)} connected; "
                                f"{len(users_to_disconnect)} to disconnect"
                            )

                            if not users_to_disconnect:
                                continue

                            # ----------------------------------------------
                            # Step 5: Evict from cache BEFORE disconnecting.
                            # If an evicted user immediately tries to
                            # reconnect after being kicked, get_user() goes
                            # back to DB and correctly rejects them.
                            # ----------------------------------------------
                            for username in users_to_disconnect:
                                user_service.evict_user(username)

                            # ----------------------------------------------
                            # Step 6: Disconnect WebSocket connections
                            # ----------------------------------------------
                            for sid, client_info in clients_snapshot.items():
                                username = client_info.get('username')
                                if username and username in users_to_disconnect:
                                    sids_to_disconnect.append((
                                        sid,
                                        client_info.get('namespace', '/'),
                                        username
                                    ))

                            for sid, namespace, username in sids_to_disconnect:
                                try:
                                    socketio.server.disconnect(
                                        sid, namespace=namespace
                                    )
                                    websocket_manager.remove_client(sid)
                                    logger.info(
                                        f"Disconnected WebSocket: {username} "
                                        f"(removed from DB)"
                                    )
                                except Exception as e:
                                    logger.warning(
                                        f"Error disconnecting WebSocket "
                                        f"{username}: {e}"
                                    )

                            # ----------------------------------------------
                            # Step 7: Disconnect SSE connections
                            # O(1) dict.get() — not a linear scan.
                            # ----------------------------------------------
                            for username in users_to_disconnect:
                                try:
                                    conn_ids = sse_snapshot.get(username, [])
                                    for conn_id in conn_ids:
                                        sse_manager.remove_connection(
                                            username, conn_id
                                        )
                                        logger.info(
                                            f"Removed SSE: {username} "
                                            f"(removed from DB)"
                                        )
                                except Exception as e:
                                    logger.warning(
                                        f"Error removing SSE for {username}: {e}"
                                    )

                            # /_v eviction — disconnect WS sids for removed users
                            for username in users_to_disconnect:
                                for sid in v_snapshot.get(username, []):
                                    try:
                                        socketio.server.disconnect(
                                            sid, namespace='/_v'
                                        )
                                        logger.info(
                                            f"Disconnected /_v: {username} "
                                            f"(removed from DB)"
                                        )
                                    except Exception as e:
                                        logger.warning(
                                            f"Error disconnecting /_v "
                                            f"{username}: {e}"
                                        )

                except Exception as e:
                    logger.error(
                        f"Error in active disconnect worker: {e}",
                        exc_info=True
                    )

            except Exception as e:
                logger.error(
                    f"Error in active disconnect loop: {e}",
                    exc_info=True
                )
                time.sleep(60)  # Back off before retrying

    worker_thread = threading.Thread(
        target=active_disconnect_loop,
        daemon=True,
        name="Active-Disconnect-Worker"
    )
    worker_thread.start()
    logger.info("Active disconnect worker started")


# ---------------------------------------------------------------------------
# Slot-sales sweep (API_CLAIMER_MODE only) — capacity CLEANUP, not the auth
# boundary. Expires sold slots at/after expires_at (removing them from the
# operator's userscripts), releases stale unpaid reservations, and securely
# wipes any lingering pending tokens. Authorization always uses the live
# expires_at>now() predicate in each request, so this sweep only frees capacity.
# ---------------------------------------------------------------------------
def _start_slot_expiry_sweep(app):
    import threading
    import time
    import logging
    logger = logging.getLogger(__name__)

    def sweep_loop():
        from app.config import Config
        from app.database import db_session
        from app.models import ApiSlot, ApiOrder
        from sqlalchemy import select, or_
        interval = max(15, int(getattr(Config, 'SLOT_SWEEP_INTERVAL_S', 60)))
        while True:
            try:
                time.sleep(interval)
                from datetime import datetime, timezone
                now = datetime.now(timezone.utc)
                affected_keys = set()
                expired_notify = []   # [(telegram_id, stake_username)] for expiry DMs
                with db_session() as s:
                    # 1) Expire sold slots whose time is up.
                    rows = s.execute(
                        select(ApiSlot).where(ApiSlot.status == 'active',
                                              ApiSlot.expires_at.isnot(None),
                                              ApiSlot.expires_at <= now)
                    ).scalars().all()
                    for slot in rows:
                        slot.status = 'expired'
                        if slot.slot_telegram_id:
                            expired_notify.append(
                                (int(slot.slot_telegram_id), slot.stake_username or 'your account'))
                    # Token hygiene: once a subscription ends we no longer need the
                    # buyer's raw Stake credential. Wipe it on EVERY expired slot
                    # that still carries one (covers this cycle's expirations AND
                    # any historically-expired rows) so a dead subscription never
                    # leaves a live Stake token sitting in the DB / pushed to scripts.
                    # The userscript already ignores non-active slots, and a reuse
                    # overwrites the token anyway — so this is pure defense-in-depth.
                    from sqlalchemy import update as _update
                    s.flush()
                    tok_wiped = s.execute(
                        _update(ApiSlot)
                        .where(ApiSlot.status == 'expired',
                               ApiSlot.stake_access_token.isnot(None))
                        .values(stake_access_token=None, token_fp=None,
                                token_valid=False)
                    ).rowcount
                    if rows:
                        from app.models import ApiAccount
                        acct_ids = {r.account_id for r in rows}
                        accts = s.execute(
                            select(ApiAccount).where(ApiAccount.id.in_(acct_ids))
                        ).scalars().all()
                        affected_keys = {a.license_key for a in accts}
                    # 2) Release stale unpaid reservations + wipe their tokens.
                    stale = s.execute(
                        select(ApiOrder).where(
                            ApiOrder.status == 'pending',
                            ApiOrder.reservation_expires_at.isnot(None),
                            ApiOrder.reservation_expires_at <= now)
                    ).scalars().all()
                    for o in stale:
                        o.status = 'reservation_expired'
                        o.enc_stake_token = None
                        o.reserved_pool_account_id = None
                        o.reserved_slot_index = None
                        o.reservation_expires_at = None
                    # 3) Belt-and-suspenders: wipe tokens on any terminal order.
                    leftover = s.execute(
                        select(ApiOrder).where(
                            ApiOrder.status.in_(('failed', 'refunded', 'reservation_expired')),
                            ApiOrder.enc_stake_token.isnot(None))
                    ).scalars().all()
                    for o in leftover:
                        o.enc_stake_token = None
                    if rows or stale or leftover or tok_wiped:
                        logger.info(f"Slot-sweep: expired={len(rows)} "
                                    f"reservations_released={len(stale)} "
                                    f"order_tokens_wiped={len(leftover)} "
                                    f"slot_tokens_wiped={tok_wiped}")
                # Push updated slot lists to affected operator scripts (removes
                # the expired slot live).
                for lk in affected_keys:
                    try:
                        from app.routes.tmc_routes import push_slots_to_account
                        push_slots_to_account(lk)
                    except Exception:
                        pass
                # Notify each affected buyer (and the admin) that their slot expired.
                if expired_notify:
                    try:
                        from app.utils.telegram import notify_bot_service
                        admin_id = getattr(Config, 'ADMIN_TELEGRAM_ID', None)
                        for tid, uname in expired_notify:
                            try:
                                notify_bot_service(
                                    tid,
                                    f"⏰ <b>Subscription expired</b>\n"
                                    f"━━━━━━━━━━━━━━━\n"
                                    f"Your slot for <b>{uname}</b> just ran out, so we've "
                                    f"<b>stopped auto-claiming</b> for it. 😔\n\n"
                                    f"💸 Every drop from now on is a code you're missing.\n"
                                    f"⚡ Renew in seconds and we're back to claiming "
                                    f"<b>24×7</b> — you never lift a finger.\n\n"
                                    f"👉 Open the app, tap <b>{uname}</b>, and hit "
                                    f"<b>Renew</b> to pick up right where you left off. 🚀")
                            except Exception:
                                pass
                            if admin_id:
                                try:
                                    notify_bot_service(
                                        int(admin_id),
                                        f"🔔 Slot expired — user <code>{tid}</code> "
                                        f"(<b>{uname}</b>). Their subscription ended.")
                                except Exception:
                                    pass
                    except Exception:
                        logger.exception("expiry notify failed (ignored)")
                # Recover any MISSED OxaPay webhooks: re-verify pending orders that
                # already have a track_id and allocate if paid (no-op without an
                # OxaPay key configured on this backend).
                try:
                    from app.routes.api_customer import reconcile_pending_orders
                    n = reconcile_pending_orders()
                    if n:
                        logger.info(f"Slot-sweep: reconciled {n} paid order(s) from missed webhooks")
                except Exception:
                    logger.exception("slot reconcile failed (ignored)")
                # Auto-fulfil backordered slots (paid, waiting on capacity) now that this
                # sweep may have freed/added slots. Idempotent; DMs the buyer on activation.
                try:
                    from app.routes.api_customer import fulfil_awaiting_capacity
                    m = fulfil_awaiting_capacity()
                    if m:
                        logger.info(f"Slot-sweep: auto-activated {m} backordered slot(s)")
                except Exception:
                    logger.exception("backorder fulfil failed (ignored)")
            except Exception as e:
                logger.error(f"Error in slot expiry sweep: {e}", exc_info=True)
                time.sleep(30)

    t = threading.Thread(target=sweep_loop, daemon=True, name="Slot-Expiry-Sweep")
    t.start()
    logger.info("Slot expiry sweep worker started (API_CLAIMER_MODE)")


# ---------------------------------------------------------------------------
# Worker 2: Cache-Sweep-Worker
# Runs every 5 minutes.
# Checks ALL cached usernames (online AND offline) against DB.
# Catches deleted users who are currently offline — the active disconnect
# worker never sees them because they have no open connections.
#
# Example gap this closes:
#   1. Alice connects → get_user() caches Alice for 3 hours
#   2. Alice closes her browser (offline)
#   3. Admin deletes Alice from DB
#   4. Active-Disconnect-Worker: Alice not in connected_users → skipped
#   5. Cache-Sweep-Worker fires after ≤5 min → Alice in cache but not in
#      DB → evict_user("alice") → her cache entry removed
#   6. Alice tries to reconnect → cache miss → DB lookup → not found → 403
# ---------------------------------------------------------------------------

def _start_cache_sweep_worker(app):
    """
    Background worker that validates ALL cached users against DB every 5 min.

    Complements Active-Disconnect-Worker (which only checks connected users).
    Ensures deleted offline users are evicted from cache promptly, preventing
    them from reconnecting using a stale cache hit.

    Does NOT disconnect anyone — it only evicts cache entries. Active sessions
    are handled by Active-Disconnect-Worker. The next connection attempt by
    an evicted user will hit the DB and be rejected.
    """
    import threading
    import time
    import logging

    logger = logging.getLogger(__name__)

    # Sweep interval: 5 minutes is a good tradeoff.
    # Deleted offline users can reconnect for at most 5 minutes after deletion.
    _SWEEP_INTERVAL = 300  # seconds

    def cache_sweep_loop():
        from app.config import Config

        while True:
            try:
                time.sleep(_SWEEP_INTERVAL)

                if Config.AUTH_DISABLED:
                    continue

                # Get immutable snapshot of ALL currently cached usernames.
                # This is the full set — both connected and offline users.
                cached_usernames = user_service.get_all_cached_usernames()

                if not cached_usernames:
                    continue

                # Single batch query — one DB round-trip for the entire cache.
                try:
                    with app.app_context():
                        from app.database import SessionLocal
                        with SessionLocal() as session:
                            valid_users = session.execute(
                                select(User.username).where(
                                    User.username.in_(cached_usernames)
                                )
                            ).scalars().all()
                            valid_users_set = set(valid_users)

                            # Transient failure guard — same logic as the
                            # active disconnect worker. If DB returns an
                            # empty set for a non-empty cache, verify the
                            # table isn't genuinely empty before evicting.
                            if not valid_users_set and cached_usernames:
                                try:
                                    db_alive = session.execute(
                                        select(func.count()).select_from(User)
                                    ).scalar()
                                    if db_alive == 0:
                                        logger.warning(
                                            "Cache sweep: DB health check "
                                            "shows 0 users — skipping "
                                            "(transient failure)"
                                        )
                                        continue
                                except Exception:
                                    logger.warning(
                                        "Cache sweep: DB health check "
                                        "failed — skipping (transient failure)"
                                    )
                                    continue

                            # Users in cache but no longer in DB
                            stale_usernames = cached_usernames - valid_users_set

                            if not stale_usernames:
                                logger.debug(
                                    f"Cache sweep: {len(cached_usernames)} "
                                    f"cached users all valid"
                                )
                                continue

                            logger.info(
                                f"Cache sweep: evicting {len(stale_usernames)} "
                                f"stale user(s) from cache"
                            )
                            for username in stale_usernames:
                                user_service.evict_user(username)
                                logger.info(
                                    f"Cache sweep: evicted '{username}' "
                                    f"(no longer in DB)"
                                )

                except Exception as e:
                    logger.error(
                        f"Error in cache sweep DB query: {e}",
                        exc_info=True
                    )

            except Exception as e:
                logger.error(
                    f"Error in cache sweep loop: {e}",
                    exc_info=True
                )
                time.sleep(60)  # Back off before retrying

    sweep_thread = threading.Thread(
        target=cache_sweep_loop,
        daemon=True,
        name="Cache-Sweep-Worker"
    )
    # API_CLAIMER_MODE: main-product username/balance cache sweep — not needed.
    if not Config.API_CLAIMER_MODE:
        sweep_thread.start()
    logger.info(
        f"Cache sweep worker started — interval {_SWEEP_INTERVAL}s"
    )


