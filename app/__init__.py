# ---------------------------------------------------------------------------
# Worker 4: License-Activation-Scanner
# Runs every Config.LICENSE_SCAN_INTERVAL seconds.
# Detects new activations, deactivations, deletions, and field changes
# (e.g. maximum_usernames) in the licenses table. Notifies the bot service
# via /nx/v3/lic-sync and /nx/v3/push, and disconnects /_tmc rooms on
# deactivation / deletion.
# ---------------------------------------------------------------------------

def _start_license_activation_scanner(app):
    import threading
    import time
    import logging

    logger = logging.getLogger(__name__)

    # 30s grace at startup so the cache (rebuild_cache_from_db) settles and
    # we don't fire spurious "newly activated" notifications for licenses
    # already present in the cache from the boot snapshot.
    STARTUP_GRACE = 30.0

    def scanner_loop():
        from app.config import Config
        from app.database import SessionLocal
        from app.license_manager import (
            active_license_cache,
            _cache_lock,
            prune_denylist,
            redact_key,
        )
        from app.models import License
        from app.utils.telegram import notify_bot_service, push_license_sync
        from sqlalchemy import select, update

        # Per-license dedup for the <0.5 admin low-balance alert. A license is
        # added here when it first crosses below 0.5 and removed once it recovers
        # to >= 0.5, so the admin gets exactly one alert per downward crossing.
        low_alerted: set = set()

        # Engaging, user-friendly "you've run out of balance" notice. Sent once
        # per drain (the negative-balance path flips the license inactive, so it
        # cannot re-fire until a manual top-up + reactivation).
        def _neg_balance_msg(bal) -> str:
            """Engaging deactivation notice that states the ACTUAL (negative)
            balance. A single large claim can overshoot the top-up, so the
            balance can be well below $0 — we show exactly how much, plus how
            much it takes to get back to positive."""
            try:
                b = float(bal)
            except (TypeError, ValueError):
                b = 0.0
            need = abs(b) + 0.01  # nudge just past zero so it reactivates
            return (
                "🪫 <b>Balance Empty — License Paused</b>\n\n"
                "Your claiming balance just went <b>negative</b>, so your license "
                "has been <b>temporarily paused</b> to keep everything running "
                "smoothly. ⏸️\n\n"
                f"💳 Current balance: <b>${b:,.2f}</b>\n"
                "<i>Your last claim was larger than the balance you had left, so "
                "it dipped below zero.</i>\n\n"
                f"🔋 Add at least <b>${need:,.2f}</b> to get back above $0 and your "
                "license switches on automatically — no waiting. 🚀\n\n"
                "Tap /topup to recharge, or message @adityaofficial96 if you need a "
                "hand. 💛"
            )

        def _deactivate_for_negative_balance(lk, info) -> bool:
            """Disable a percentage license whose balance went negative, then
            tell the user (engagingly) to recharge. Handles DB, in-process cache,
            the /_tmc room, the bot cache sync, and the user notification — so the
            scanner's generic active-transition path must SKIP it (avoids a second
            'LICENSE DEACTIVATED' message).

            Returns True only if the DB write committed. On a DB failure it does
            NOT pop the cache, disconnect, sync, or notify — it returns False so
            the caller leaves the license untouched and the next scan cycle
            retries cleanly (no duplicate 'paused' message, no DB/notify desync)."""
            tid = int(info.get('telegram_id') or 0)
            try:
                with app.app_context():
                    with SessionLocal() as session:
                        session.execute(
                            update(License)
                            .where(License.license_key == lk)
                            .values(active=False, deactivated_at=func.now())
                        )
                        session.commit()
            except Exception as exc:
                logger.warning(
                    f"negative-balance deactivate failed for {redact_key(lk)}: {exc}"
                )
                return False
            with _cache_lock:
                active_license_cache.pop(lk, None)
            try:
                from app.routes.tmc_routes import disconnect_license_room
                disconnect_license_room(lk)
            except Exception:
                pass
            try:
                push_license_sync(lk, tid, False)
            except Exception:
                pass
            if tid:
                try:
                    notify_bot_service(tid, _neg_balance_msg(info.get('available_balance')))
                except Exception:
                    pass
            logger.info(
                f"BALANCE_DEACTIVATE | license={lk} | telegram_id={tid} | "
                f"balance={info.get('available_balance')}"
            )
            return True

        def _admin_low_balance_alert(lk, info):
            """DM ADMIN_TELEGRAM_ID that a percentage license is below $0.50."""
            admin_raw = (os.environ.get('ADMIN_TELEGRAM_ID') or '').strip()
            if not admin_raw:
                return
            try:
                admin_id = int(admin_raw)
            except (TypeError, ValueError):
                return
            tid = int(info.get('telegram_id') or 0)
            bal = info.get('available_balance')
            pct = info.get('deduction_percentage')
            msg = (
                "🔔 <b>LOW BALANCE ALERT</b>\n\n"
                "A license is running low and will need a top-up soon.\n\n"
                f"👤 User ID: <code>{tid}</code>\n"
                f"🔑 License: <code>{lk}</code>\n"
                f"💰 Balance: <b>${(bal if bal is not None else 0):.4f}</b>\n"
                f"📉 Deduction: <b>{(pct if pct is not None else 0):g}%</b> per claim"
            )
            try:
                notify_bot_service(admin_id, msg)
            except Exception:
                pass
            logger.info(
                f"LOW_BALANCE_ALERT | license={lk} | telegram_id={tid} | balance={bal}"
            )

        # Wait once before first scan
        time.sleep(STARTUP_GRACE)

        last_known: dict = {}
        # Build initial baseline against the live DB. Compare to the cache
        # which was loaded at startup so an activation that landed AFTER
        # boot-time snapshot still emits a notification (R-02).
        first_run = True

        while True:
            try:
                time.sleep(max(2, int(getattr(Config, 'LICENSE_SCAN_INTERVAL', 10))))

                with app.app_context():
                    with SessionLocal() as session:
                        all_lics = session.execute(select(
                            License.license_key, License.active, License.banned,
                            License.telegram_id, License.maximum_usernames,
                            License.theclaimers_count, License.manager_id,
                            License.available_balance, License.deduction_percentage,
                        )).all()
                        current = {
                            l.license_key: {
                                'active': bool(l.active),
                                'telegram_id': int(l.telegram_id),
                                'maximum_usernames': int(l.maximum_usernames or Config.MAX_CONNECTIONS_PER_LICENSE),
                                'theclaimers_count': int(l.theclaimers_count or 0),
                                'banned': bool(l.banned),
                                'manager_id': (l.manager_id or ''),
                                'available_balance': (float(l.available_balance) if l.available_balance is not None else 0.0),
                                'deduction_percentage': (float(l.deduction_percentage) if l.deduction_percentage is not None else None),
                            }
                            for l in all_lics
                        }

                if first_run:
                    # R-02: compare DB to cache to catch any activation that
                    # landed between rebuild_cache_from_db() and scanner start.
                    with _cache_lock:
                        cache_keys = set(active_license_cache.keys())
                    for lk, info in current.items():
                        in_cache = lk in cache_keys
                        if info['active'] and not info['banned'] and not in_cache:
                            # Newly activated since cache snapshot — notify
                            _emit_activation_notice(lk, info, notify_bot_service,
                                                    push_license_sync, redact_key)
                            with _cache_lock:
                                active_license_cache[lk] = {
                                    'active': True,
                                    'telegram_id': info['telegram_id'],
                                    'maximum_usernames': info['maximum_usernames'],
                                    'theclaimers_count': info['theclaimers_count'],
                                    'manager_id': info.get('manager_id', ''),
                                    'available_balance': info.get('available_balance'),
                                    'deduction_percentage': info.get('deduction_percentage'),
                                    'banned': False,
                                }
                        # Seed the low-balance dedup set so we DON'T fire alerts
                        # for licenses already below 0.5 at boot — we only alert
                        # on a fresh downward crossing after startup.
                        _pct = info.get('deduction_percentage')
                        _bal = info.get('available_balance')
                        if _pct is not None and _bal is not None and _bal < 0.5:
                            low_alerted.add(lk)
                    last_known = current
                    first_run = False
                    prune_denylist()
                    continue

                # Deletions: in last_known but missing from current
                for lk in set(last_known.keys()) - set(current.keys()):
                    prev = last_known.get(lk) or {}
                    telegram_id = prev.get('telegram_id') or 0
                    try:
                        from app.routes.tmc_routes import emit_license_deleted
                        emit_license_deleted(lk)
                    except Exception:
                        pass
                    with _cache_lock:
                        active_license_cache.pop(lk, None)
                    push_license_sync(lk, telegram_id, None)

                # Changes
                for lk, info in current.items():
                    prev = last_known.get(lk)
                    pct = info.get('deduction_percentage')
                    bal = info.get('available_balance')
                    balance_deactivated = False

                    # ── Percentage-license balance management ──────────────
                    # After-Claims licenses (deduction_percentage IS NULL) are
                    # exempt: no balance to deduct, police, or alert on (their
                    # default balance of 0 must never trip the <0.5 alert).
                    if pct is not None and bal is not None:
                        # Negative balance → temporarily disable + recharge nudge.
                        # Guarded on `active` so it fires exactly once per drain.
                        # Only mark it deactivated if the DB write committed;
                        # otherwise leave it as-is and retry next cycle (no
                        # spurious notice, no DB/notify desync).
                        if bal < 0 and info['active']:
                            if _deactivate_for_negative_balance(lk, info):
                                info['active'] = False
                                balance_deactivated = True
                        # Low-balance admin alert, deduped via low_alerted; the
                        # flag clears once the balance recovers to >= 0.5 so a
                        # later drop alerts again. Gated on `active`: a brand-new
                        # (or paused) prepaid license sits at $0 by design and is
                        # NOT "running low" — only an ACTIVE, in-use license that
                        # dips below $0.50 is worth alerting on.
                        if bal < 0.5 and info['active']:
                            if lk not in low_alerted:
                                _admin_low_balance_alert(lk, info)
                                low_alerted.add(lk)
                        else:
                            low_alerted.discard(lk)
                    else:
                        low_alerted.discard(lk)

                    # Always refresh cache for active+not-banned (now carrying
                    # available_balance + deduction_percentage too).
                    if info['active'] and not info['banned']:
                        with _cache_lock:
                            active_license_cache[lk] = {
                                'active': True,
                                'telegram_id': info['telegram_id'],
                                'maximum_usernames': info['maximum_usernames'],
                                'theclaimers_count': info['theclaimers_count'],
                                'manager_id': info.get('manager_id', ''),
                                'available_balance': bal,
                                'deduction_percentage': pct,
                                'banned': False,
                            }
                    else:
                        with _cache_lock:
                            active_license_cache.pop(lk, None)

                    if prev is None:
                        # Brand new row — DON'T notify yet (it was just created
                        # via /api/xr9k/lic/reg, which leaves it inactive).
                        last_known[lk] = info
                        continue

                    if balance_deactivated:
                        # The negative-balance path already updated the DB, the
                        # cache, the /_tmc room, the bot cache, and notified the
                        # user. Skip the generic active-transition handling so the
                        # user gets ONE (recharge) message, not two.
                        continue

                    # Only ACTIVE transitions sync to the bot. We deliberately do
                    # NOT push on every balance change: the bot never reads the
                    # cached balance for a decision (it live-fetches from the
                    # backend on /balance), so a per-cycle push would be a pure
                    # detached-curl fork storm under load with zero benefit. The
                    # transition push carries bal/pct so activation keeps the
                    # bot's fallback copy reasonably fresh.
                    if prev.get('active') != info['active']:
                        push_license_sync(
                            lk, info['telegram_id'], bool(info['active']),
                            info['theclaimers_count'], info['maximum_usernames'],
                            bal, pct,
                        )

                        if info['active'] and not prev['active']:
                            _emit_activation_notice(lk, info, notify_bot_service,
                                                    push_license_sync, redact_key)
                        elif not info['active'] and prev['active']:
                            # Newly deactivated — disconnect /_tmc room
                            try:
                                from app.routes.tmc_routes import disconnect_license_room
                                disconnect_license_room(lk)
                            except Exception:
                                pass
                            notify_bot_service(
                                info['telegram_id'],
                                "🔴 <b>License Deactivated</b>\n"
                                "━━━━━━━━━━━━━━━\n"
                                f"🔑 <code>{redact_key(lk)}</code>\n\n"
                                "Your license has been switched off. Tap 🛟 Support "
                                "(@adityaofficial96) if you think this is a mistake."
                            )

                # Drop deleted licenses from the low-balance dedup set so it can
                # never grow unbounded as licenses churn over time.
                low_alerted.intersection_update(current.keys())
                last_known = current
                prune_denylist()

            except Exception as e:
                logger.error(f"License scanner error: {e}", exc_info=True)

    def _emit_activation_notice(lk, info, notify_bot_service, push_license_sync, redact_key):
        try:
            push_license_sync(
                lk, info['telegram_id'], True,
                info['theclaimers_count'], info['maximum_usernames'],
                info.get('available_balance'), info.get('deduction_percentage'),
            )
            notify_bot_service(
                info['telegram_id'],
                "🟢 <b>License Activated</b>\n"
                "━━━━━━━━━━━━━━━\n"
                f"🔑 <code>{redact_key(lk)}</code>\n\n"
                "You're all set! Use /drop to broadcast codes, /connected to see "
                "your claimers, and /count to track results.\n\nWelcome aboard! 🚀"
            )
        except Exception as exc:
            logger.warning(f"_emit_activation_notice: {exc}")

    scanner_thread = threading.Thread(
        target=scanner_loop,
        daemon=True,
        name="License-Scanner",
    )
    # API_CLAIMER_MODE: the License-Scanner is main-product (queries the licenses
    # table + balance and pushes to the bot) — do NOT start it against the new DB.
    if not Config.API_CLAIMER_MODE:
        scanner_thread.start()
        logger.info("License-Scanner started")
    else:
        logger.info("License-Scanner NOT started (API_CLAIMER_MODE)")
