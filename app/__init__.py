# ---------------------------------------------------------------------------
# Eventlet WSGI noise filter
# ---------------------------------------------------------------------------
# Suppresses eventlet's harmless EBADF warnings on socket shutdown.
#
# What these look like (this is the noise we're dropping):
#   server=kciade.online//socket.io/ client=10.26.182.132:60926 \
#       socket shutdown error: [Errno 9] Bad file descriptor
#
# Why they appear:
#   When a WebSocket connection ends (browser close, NAT timeout, CF
#   disconnect, etc.), eventlet's WSGI cleanup runs socket.shutdown(SHUT_WR)
#   on the connection. Often the kernel has already reaped the FD by then,
#   so shutdown() returns EBADF. The error is benign — the socket is gone,
#   the shutdown would have been a no-op. eventlet logs it anyway, which at
#   scale (hundreds of disconnects/hour from natural client churn) spams the
#   log and obscures real warnings.
#
# Why this is safe:
#   * The error message is generated by eventlet INSIDE its cleanup path —
#     the connection is already closed; nothing functional is affected.
#   * We filter ONLY this specific substring; every other warning, error,
#     and info message from eventlet, gunicorn, and the app passes through
#     unmodified.
#   * The filter is attached to gunicorn.error, eventlet, and eventlet.wsgi
#     loggers (eventlet's wsgi.Server.log routes through whichever was
#     passed in by gunicorn).
#   * The 10.X.X.X IPs in these messages are Render's internal proxy IPs,
#     not end-user IPs — they provide no actionable signal even if read.
# ---------------------------------------------------------------------------
class _EventletShutdownNoiseFilter(logging.Filter):
    _SUPPRESS_SUBSTRINGS = (
        'socket shutdown error: [Errno 9] Bad file descriptor',
    )

    def filter(self, record: logging.LogRecord) -> bool:
        # Never block a log line if we can't render it — fail-safe.
        try:
            msg = record.getMessage()
        except Exception:
            return True
        return not any(s in msg for s in self._SUPPRESS_SUBSTRINGS)


_NOISE_FILTER = _EventletShutdownNoiseFilter()
for _name in ('gunicorn.error', 'eventlet', 'eventlet.wsgi'):
    logging.getLogger(_name).addFilter(_NOISE_FILTER)


